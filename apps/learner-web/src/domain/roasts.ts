export function pickRoastMessage(
  random: () => number = Math.random,
  previous?: string,
): string {
  const candidates = previous
    ? roastMessages.filter((message) => message !== previous)
    : roastMessages;
  const index = Math.floor(random() * candidates.length);
  return candidates[index] ?? roastMessages[0];
}
